/**
 * How the stored presets (`presets.ts`) are made (design § 9): rough starts spun up for 520 model weeks, or derived
 * from another preset. Only `test/presets.slow.test.ts` runs this (it regenerates and compares the stored data, and
 * prints a ready-to-paste file with `UPDATE_PRESETS=1`); the game itself never spins up at run time.
 */
import { habitatDef, type Habitat } from './habitats';
import { applyAction, cloneSim, makeSim, sample, stepWeek, total, type Action, type Env, type Sim } from './model';

export const PRESET_IDS = ['pond.lively', 'pond.young', 'pond.plankton', 'pond.openfish', 'pond.green', 'pond.bare', 'meadow.lively', 'meadow.poor', 'meadow.nofox', 'meadow.bare'] as const;
export type PresetId = (typeof PRESET_IDS)[number];

/** A stored start: the snapshot at week 0 and the 8 weekly samples before it (the chart's history; [] for bare). */
export interface Preset {
  readonly habitat: Habitat;
  readonly sim: Sim;
  readonly history: readonly (readonly number[])[];
}

export const presetHabitat = (id: PresetId): Habitat => (id.startsWith('pond.') ? 'pond' : 'meadow');

/** Runs `weeks` weeks and returns the end state restarted at week 0 (bookkeeping rebased) and the last 8 samples. */
function spin(start: Sim, habitat: Habitat, weeks: number, override?: Partial<Env>): Preset {
  const hab = habitatDef(habitat);
  const s = cloneSim(start);
  s.week = 0;
  const samples: number[][] = [];
  for (let w = 0; w < weeks; w++) {
    samples.push(sample(s));
    stepWeek(s, hab, override ? { override } : {});
  }
  // As in the calibration prototype: the week counter restarts at 0 (the juvenile rings are kept as they are).
  s.week = 0;
  s.imp = total(s);
  s.exp = 0;
  s.wimp = s.w;
  s.wexp = 0;
  return { habitat, sim: s, history: samples.slice(-8) };
}

const pondStart = (T: number, b: Record<string, number>): Sim => {
  const sum = Object.values(b).reduce((x, y) => x + y, 0);
  return makeSim('pond', { n: 20_000, d: Math.max(0, T - sum - 20_000), b });
};
const meadowStart = (b: Record<string, number>): Sim => makeSim('meadow', { n: 20_000, d: 150_000, w: 150_000, b });

const MEADOW_LIVELY = { grass: 100_000, flowers: 80_000, clover: 40_000, aphids: 5_000, ladybirds: 2_000, rabbits: 15_000, foxes: 2_000, worms: 15_000 };

/** Builds every preset from its recipe (a few hundred milliseconds). */
export function buildPresets(): Record<PresetId, Preset> {
  const pondLively = spin(pondStart(500_000, { algae: 40_000, bluegreen: 1_000, duckweed: 1_000, pondweed: 250_000, fleas: 30_000, snails: 15_000, minnows: 30_000 }), 'pond', 520);
  const green = cloneSim(pondLively.sim);
  green.cond[1] = 3; // runoff high for two years
  const meadowLively = spin(meadowStart(MEADOW_LIVELY), 'meadow', 520);
  const nofox = cloneSim(meadowLively.sim);
  const removeFoxes: Action = { week: 0, kind: 'remove', species: 'foxes', share: 100 };
  applyAction(nofox, habitatDef('meadow'), removeFoxes);
  const bare = (habitat: Habitat, s: Sim): Preset => ({ habitat, sim: s, history: [] });
  return {
    'pond.lively': pondLively,
    'pond.young': spin(pondStart(400_000, { algae: 60_000 }), 'pond', 520),
    'pond.plankton': spin(pondStart(400_000, { algae: 60_000, fleas: 30_000 }), 'pond', 520),
    'pond.openfish': spin(pondStart(500_000, { algae: 60_000, fleas: 30_000, minnows: 30_000 }), 'pond', 520),
    'pond.green': spin(green, 'pond', 104),
    'pond.bare': bare('pond', makeSim('pond', { n: 30_000, d: 100_000, b: { algae: 5_000 } })),
    'meadow.lively': meadowLively,
    'meadow.poor': spin(meadowStart({ grass: 60_000, flowers: 60_000, worms: 10_000 }), 'meadow', 520, { input: 20 }),
    'meadow.nofox': spin(nofox, 'meadow', 156),
    'meadow.bare': bare('meadow', makeSim('meadow', { n: 20_000, d: 150_000, w: 150_000, b: { grass: 5_000, flowers: 5_000, clover: 5_000 } }))
  };
}

/** The generated `presets.ts` source for a set of presets. */
export function presetsSource(p: Record<PresetId, Preset>): string {
  const lines = [
    '/**',
    ' * Stored presets of the model `eco-1` (design § 9). GENERATED by `test/presets.slow.test.ts` from `spinup.ts`',
    ' * (`UPDATE_PRESETS=1 pnpm vitest run packages/games/ecosystem/test/presets.slow.test.ts`); never edit by hand.',
    ' */',
    "import type { Preset, PresetId } from './spinup';",
    '',
    'export const PRESETS: Readonly<Record<PresetId, Preset>> = {'
  ];
  PRESET_IDS.forEach((id, k) => {
    const x = p[id];
    lines.push(`  '${id}': {`, `    habitat: '${x.habitat}',`, `    sim: ${JSON.stringify(x.sim)},`, `    history: ${JSON.stringify(x.history)}`, `  }${k < PRESET_IDS.length - 1 ? ',' : ''}`);
  });
  lines.push('};', '');
  return lines.join('\n');
}
