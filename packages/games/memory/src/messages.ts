/** A tuple of exactly one translated name per symbol id (length checked by the compiler). */
type NamesFor<T extends readonly unknown[]> = { readonly [K in keyof T]: string };
type SymbolNames = NamesFor<typeof SYMBOL_IDS>;

const symbols = (names: SymbolNames): Record<string, string> =>
  Object.fromEntries(SYMBOL_IDS.map((id, i) => [`symbol.${id}`, names[i] as string]));

