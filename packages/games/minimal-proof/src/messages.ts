import type { GameMessages } from '@wp/game-core';

/**
 * Translations for Proof Chain. Counts are phrased as "label: {n}" so no plural forms are
 * needed. Statement symbols (A, ¬C) and logic signs (→ ∧ ∨ ¬) are language-neutral; formulas
 * are always laid out left-to-right. Themed nouns (`vocab.*`) only decorate the letters.
 */

const VOCAB_IDS = ['key', 'coin', 'lamp', 'map', 'boat', 'bridge', 'torch', 'rope', 'ladder', 'compass'] as const;

function withVocab(base: Record<string, string>, nouns: readonly string[], negated: readonly string[]): Record<string, string> {
  const out: Record<string, string> = { ...base };
  VOCAB_IDS.forEach((id, i) => {
    out[`vocab.${id}`] = nouns[i] as string;
    out[`vocab.${id}.not`] = negated[i] as string;
  });
  return out;
}

